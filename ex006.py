n = int(input('Digite um número: '))

print(f'O dobro de {n} é {n * 2}.')
print(f'O triplo de {n} é {n * 3}.')
print(f'A raiz quadrada de {n} é {n ** 0.5}.')
print(f'{n} elevado ao quadrado é {n ** 2}.')
print(f'A divisão inteira de {n} por 2 é {n // 2}.')
print(f'O resto da divisão de {n} por 2 é {n % 2}.')